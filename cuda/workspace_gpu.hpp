/**
 * workspace_gpu.hpp
 * R5.3: host driver of the GPU workspace sampling (chunking, streams, errors).
 */
#pragma once

#include <atomic>
#include <cstddef>
#include <string>

#include "compute/workspace.hpp"
#include "fk_kernel.cuh"

namespace gpu {

/// Runs the sampling on the GPU. Returns true when the GPU did the work (res filled).
/// Returns false with `reason` set when the CPU must run instead (no device, GPU dead,
/// not enough VRAM, out of memory below the minimum chunk, sticky CUDA error).
/// Throws std::invalid_argument when an explicit budget_bytes is too small for the grid,
/// gpu::CudaError for non-sticky CUDA errors.
bool workspace_gpu(const FkPathTables& tables, const compute::SamplerTables& smp,
                   const compute::WorkspaceGrid& grid, const compute::WorkspaceOptions& opt,
                   std::size_t total, const std::atomic<bool>* cancel,
                   const compute::ProgressFn& progress, compute::WorkspaceResult& res,
                   std::string& reason);

/// Debug: q for samples [start, start + n) generated by the device (row-major, n x n_dof).
void sample_q_gpu(const compute::SamplerTables& smp, std::size_t start, std::size_t n,
                  float* out);

}  // namespace gpu
